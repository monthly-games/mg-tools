@marketing.command("plan")
@click.option("--game", "-g", required=True, help="Game ID")
@click.option("--template", "-t",
              type=click.Choice(["soft_launch", "global_launch", "retention_focused", "monetization_test"]),
              default="soft_launch", help="Campaign template")
@click.option("--channels", "-c", multiple=True,
              default=["google_ads", "facebook_ads"],
              help="Marketing channels to use")
@click.option("--output", "-o", type=click.Path(), help="Output file")
@click.pass_context
def create_plan(ctx, game, template, channels, output):
    """Create marketing campaign plan"""
    service = MarketingService()

    plan = service.generate_campaign_plan(game, template, list(channels))

    if output:
        with open(output, "w") as f:
            json.dump(plan, f, indent=2)
        click.echo(f"Campaign plan saved to: {output}")
    else:
        click.echo("\nCampaign Plan:")
        click.echo("=" * 60)
        click.echo(f"Game: {plan['game_id']}")
        click.echo(f"Template: {plan['template']}")
        click.echo(f"Goal: {plan['goal']}")
        click.echo(f"\nBudget:")
        click.echo(f"  Daily: ${plan['budget']['daily']}")
        click.echo(f"  Total: ${plan['budget']['total']} ({plan['budget']['duration_days']} days)")
        click.echo(f"\nGeo Targets: {', '.join(plan['geo_targets'])}")
        click.echo(f"KPIs: {', '.join(plan['kpis'])}")
        click.echo(f"\nChannels:")
        for ch in plan["channels"]:
            click.echo(f"  - {ch['name']}: ${ch['budget_allocation']}/day")


