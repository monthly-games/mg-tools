# Click commands
@click.group("analytics")
def analytics():
    """Analytics and marketing commands"""
    pass


@analytics.command("setup")
@click.option("--game", "-g", required=True, help="Game ID")
@click.option("--output", "-o", type=click.Path(), help="Output directory")
@click.pass_context
def setup_analytics(ctx, game, output):
    """Generate analytics configuration files"""
    service = AnalyticsService()

    output_dir = Path(output) if output else Path(f"./analytics_{game}")
    output_dir.mkdir(parents=True, exist_ok=True)

    # Events schema
    events = service.generate_events_schema(game)
    with open(output_dir / "events_schema.json", "w") as f:
        json.dump(events, f, indent=2)
    click.echo(f"  Created: events_schema.json")

    # BigQuery schema
    bq_schema = service.generate_bigquery_schema(game)
    with open(output_dir / "bigquery_schema.sql", "w") as f:
        f.write(bq_schema)
    click.echo(f"  Created: bigquery_schema.sql")

    # Dashboard config
    dashboard = service.generate_dashboard_config(game)
    with open(output_dir / "dashboard_config.json", "w") as f:
        json.dump(dashboard, f, indent=2)
    click.echo(f"  Created: dashboard_config.json")

    click.echo(f"\nAnalytics config generated at: {output_dir}")


@analytics.command("kpis")
def list_kpis():
    """List standard game KPIs"""
    config = AnalyticsConfig()

    click.echo("\nStandard Game KPIs:")
    click.echo("=" * 50)
    for key, desc in config.KPIS.items():
        click.echo(f"  {key:25} {desc}")


@analytics.command("events")
def list_events():
    """List standard analytics events"""
    config = AnalyticsConfig()

    click.echo("\nStandard Analytics Events:")
    click.echo("=" * 50)
    for event, spec in config.STANDARD_EVENTS.items():
        params = ", ".join(spec["params"]) if spec["params"] else "(none)"
        click.echo(f"  {event:30} params: {params}")


