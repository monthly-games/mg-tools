    def generate_campaign_plan(
        self,
        game_id: str,
        template: str,
        channels: List[str],
    ) -> Dict[str, Any]:
        """Generate marketing campaign plan"""
        if template not in self.CAMPAIGN_TEMPLATES:
            return {"error": f"Unknown template: {template}"}

        tpl = self.CAMPAIGN_TEMPLATES[template]

        plan = {
            "game_id": game_id,
            "template": template,
            "created_at": datetime.now().isoformat(),
            "budget": {
                "daily": tpl["budget_daily"],
                "total": tpl["budget_daily"] * tpl["duration_days"],
                "duration_days": tpl["duration_days"],
            },
            "geo_targets": tpl["geo_targets"],
            "goal": tpl["goal"],
            "kpis": tpl["kpis"],
            "channels": [],
        }

        for channel in channels:
            if channel in self.CHANNELS:
                ch = self.CHANNELS[channel]
                plan["channels"].append({
                    "id": channel,
                    "name": ch["name"],
                    "platforms": ch["platforms"],
                    "recommended_campaign_type": ch["campaign_types"][0],
                    "recommended_bidding": ch["bidding_strategies"][0],
                    "budget_allocation": tpl["budget_daily"] / len(channels),
                })

        return plan

